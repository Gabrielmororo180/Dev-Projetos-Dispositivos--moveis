type MockEntry = Omit<Transaction, 'id' | 'data'> & { dia: number; mes: 'atual' | 'anterior' };

// As datas são geradas relativas ao mês atual para que as telas sempre tenham dados,
// independente de quando o app for aberto. No mês atual, nenhuma data passa de hoje.
function mockDate(mes: MockEntry['mes'], dia: number, today = new Date()): string {
  if (mes === 'atual') {
    return toISODate(
      new Date(today.getFullYear(), today.getMonth(), Math.min(dia, today.getDate())),
    );
  }
  return toISODate(new Date(today.getFullYear(), today.getMonth() - 1, dia));
}

